const output = process.env.PLAYWRIGHT_ARTIFACT_DIR || 'artifacts/tablet';
const zeroInput = { moveX: 0, moveForward: 0, steer: 0, throttle: 0, brake: 0, handbrake: false };
async function expectStopped(page: Page) {
  const before = (await read(page)).position;
  await page.waitForTimeout(350);
  const after = (await read(page)).position;
  expect(Math.hypot(after.x - before.x, after.z - before.z)).toBeLessThan(.03);
}
async function expectInViewport(page: Page, selector: string) {
  const box = await page.locator(selector).first().boundingBox(), viewport = page.viewportSize()!;
  expect(box).not.toBeNull();
  expect(box!.x).toBeGreaterThanOrEqual(0); expect(box!.y).toBeGreaterThanOrEqual(0);
  expect(box!.x + box!.width).toBeLessThanOrEqual(viewport.width + 1);
  expect(box!.y + box!.height).toBeLessThanOrEqual(viewport.height + 1);
}

test('tablet touch-only restoration, simultaneous driving controls, town loop, recovery and saved build', async ({ page, baseURL }) => {
  const errors: string[] = [], failed: string[] = [], external: string[] = [];
  const allowedOrigin = new URL(baseURL!).origin;
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('requestfailed', request => failed.push(request.url()));
  page.on('request', request => { if (/^https?:/.test(request.url()) && new URL(request.url()).origin !== allowedOrigin) external.push(request.url()); });
  await page.addInitScript(() => {
    (window as any).__touchKeyboardEvents = 0;
    (window as any).__touchLockRequests = 0;
    window.addEventListener('keydown', () => { (window as any).__touchKeyboardEvents++; });
    const original = Element.prototype.requestPointerLock;
    Element.prototype.requestPointerLock = function (...args) { (window as any).__touchLockRequests++; return original.apply(this, args); };
  });
  mkdirSync(output, { recursive: true });
  const touch = await bootTablet(page, `${output}/startup-landscape.png`);
  await page.screenshot({ path: `${output}/on-foot-landscape.png` });
  await touchWalk(touch, -18.2, 14.1);
  await touch.joystick(0, 0);
  await touchInspect(touch, -15, 12, 'shell-hachiro');
  await touch.releaseStick();
  await expect(page.locator('#touch-controls')).toBeHidden();
  await touch.tap('[data-buy="shell-hachiro"]');
  await touch.tap('[data-buy="shell-hachiro"]');
  expect((await read(page)).state.cars).toHaveLength(1);
  await closeTabletPanel(touch);
  await touchWalk(touch, -31, 16); await touchWalk(touch, -33, 2);
  await touchInspect(touch, -36, 2, 'rack-engines');
  await touch.tap('[data-buy="part-i4-stock"]');
  await touch.tap('[data-buy="part-i4-stock"]');
  expect((await read(page)).state.inventory).toHaveLength(1);
  await closeTabletPanel(touch);
  await touchWalk(touch, -33, 8); await touchInspect(touch, -36, 8, 'rack-wheels');
  await touch.tap('[data-buy="part-street-1"]'); await closeTabletPanel(touch);
  await touchWalk(touch, -33, 14); await touchInspect(touch, -36, 14, 'rack-paint');
  await touch.tap('[data-buy="part-paint-saffron"]'); await closeTabletPanel(touch);
  await touchWalk(touch, -31, -3); await touchWalk(touch, -24, -3); await touchWalk(touch, -24, -13.5);
  await touchInspect(touch, -26.4, -15, 'workbench');
  await touch.tap('[data-install="instance-part-i4-stock"]');
  await touch.tap('[data-install="instance-part-street-1"]');
  await touch.tap('[data-paint="paint-saffron"]');
  await expect(page.locator('.build-status')).toContainText('READY FOR THE ROAD');
  await page.waitForTimeout(700); await page.screenshot({ path: `${output}/garage-landscape.png` });
  await closeTabletPanel(touch);
  await touchWalk(touch, -22.6, -13); await touchInspect(touch, -20, -13, 'garage-car');
  expect((await read(page)).mode).toBe('drive');
  for (const selector of ['#touch-stick', '#touch-throttle', '#touch-brake', '#touch-handbrake', '#recover', '#pause-button']) await expectInViewport(page, selector);
  await page.screenshot({ path: `${output}/driving-garage.png` });
  const loop = (await read(page)).loop;
  await touchDrivePath(touch, loopPath(loop[2].x, loop[3].z), `${output}/driving-landscape.png`);
  await stopTablet(touch);
  expect((await read(page)).lapComplete).toBe(true);
  const lapSeconds = (await read(page)).lapElapsed;
  await touch.joystick(.7, 0);
  await touch.tap('#recover');
  expect((await read(page)).position.z).toBeCloseTo(0, 0);
  expect((await read(page)).touchInput).toEqual(zeroInput);
  await touch.release();
  // Brake becomes reverse from rest; handbrake is independently held to stop.
  await touch.hold('#touch-brake', 4, true); await page.waitForTimeout(800);
  expect((await read(page)).speed).toBeLessThan(-.2);
  await touch.up(4); await stopTablet(touch);
  await expect(page.locator('#touch-interact')).toBeEnabled(); await touch.tap('#touch-interact');
  expect((await read(page)).mode).toBe('foot');
  const before = await read(page);
  expect(await page.evaluate(() => (window as any).__touchKeyboardEvents)).toBe(0);
  expect(await page.evaluate(() => (window as any).__touchLockRequests)).toBe(0);
  await page.reload(); await expect(page.locator('#begin')).toBeEnabled();
  expect((await read(page)).state).toEqual(before.state);
  expect((await read(page)).roads).toEqual(before.roads);
  expect((await read(page)).mode).toBe('foot');
  expect(errors).toEqual([]); expect(failed).toEqual([]); expect(external).toEqual([]);
  writeFileSync(`${output}/touch-acceptance.json`, JSON.stringify({ testedURL: page.url(), viewport: page.viewportSize(), deviceScaleFactor: 2, nativeTouch: true, keyboardEvents: 0, pointerLockRequests: 0, lapSeconds, state: before.state, errors, failed, external }, null, 2));
});

test('tablet independent fingers, cancel, lost capture, pause and rotation clear held input', { tag: '@deployment' }, async ({ page }) => {
  const touch = await bootTablet(page);
  await touch.joystick(0, -1);
  await expect.poll(async () => (await read(page)).touchInput.moveForward).toBeGreaterThan(.9);
  const before = await read(page);
  await touch.look(.35, -.12);
  expect((await read(page)).touchInput.moveForward).toBeGreaterThan(.9);
  expect(Math.abs((await read(page)).yaw - before.yaw)).toBeGreaterThan(.25);
  expect((await read(page)).position.z).toBeLessThan(before.position.z);
  await touch.tap('#pause-button', 9, false);
  await expect(page.locator('[data-action="resume"]')).toBeVisible();
  expect((await read(page)).touchInput).toEqual(zeroInput);
  await touch.release(); await expectStopped(page);
  await touch.tap('[data-action="resume"]'); await expectStopped(page);
  await touch.joystick(.6, -.7); await touch.cancel();
  await expect.poll(async () => (await read(page)).touchInput).toEqual(zeroInput); await expectStopped(page);
  // Releasing real pointer capture must not leave a thumbstick latched.
  await page.locator('#touch-stick').evaluate(element => element.addEventListener('pointerdown', event => { (window as any).__stickPointer = (event as PointerEvent).pointerId; }, { once: true }));
  await touch.joystick(0, -1);
  await page.locator('#touch-stick').evaluate(element => element.releasePointerCapture((window as any).__stickPointer));
  await touch.joystick(.2, -.8);
  await expect.poll(async () => (await read(page)).touchInput).toEqual(zeroInput);
  await touch.release();
  await touch.joystick(0, -1);
  await page.setViewportSize({ width: 820, height: 1180 });
  await expect.poll(async () => (await read(page)).touchInput).toEqual(zeroInput);
  await touch.release();
  if ((await read(page)).paused) await touch.tap('[data-action="resume"]');
  await expectStopped(page);
  for (const selector of ['#touch-stick', '#touch-interact', '#pause-button']) await expectInViewport(page, selector);
  mkdirSync(output, { recursive: true }); await page.screenshot({ path: `${output}/on-foot-portrait.png` });
  await touch.joystick(0, -1); await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  expect((await read(page)).paused).toBe(true); expect((await read(page)).touchInput).toEqual(zeroInput);
  await touch.release(); await touch.tap('[data-action="resume"]'); await expectStopped(page);
});

