  expect((await read(page)).touchEnabled).toBe(false);
  await touch.tap('[data-action="touch-controls"]');
  expect((await read(page)).touchEnabled).toBe(true);
  await page.setViewportSize({ width: 1024, height: 768 });
  await expectInViewport(page, '[data-action="resume"]');
  await touch.tap('[data-action="resume"]');
  for (const selector of ['#touch-stick', '#touch-interact', '#pause-button']) await expectInViewport(page, selector);
  await page.screenshot({ path: `${output}/on-foot-1024.png` });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
